namespace LabFusion.UI.Elements;

/// <summary>
/// Indicates the direction that children are displayed for a UI element.
/// </summary>
public enum UIDirection
{
    /// <summary>
    /// Children are displayed from the top down.
    /// </summary>
    Column,

    /// <summary>
    /// Children are displayed from the bottom up.
    /// </summary>
    ColumnReverse,

    /// <summary>
    /// Children are displayed from left to right.
    /// </summary>
    Row,

    /// <summary>
    /// Children are displayed from right to left.
    /// </summary>
    RowReverse
}
